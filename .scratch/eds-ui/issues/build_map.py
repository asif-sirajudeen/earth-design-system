#!/usr/bin/env python3
"""Regenerate MAP.md from the issue files. Run: python3 build_map.py"""
import re
from pathlib import Path

ROOT = Path(__file__).parent


def field(text, name):
    m = re.search(rf"^\*\*{name}:\*\*\s*(.*)$", text, re.M)
    return m.group(1).strip().strip("`") if m else ""


issues = {}
for f in sorted(ROOT.glob("*/*.md")):
    text = f.read_text()
    num = f.name[:2]
    title = re.search(r"^# \d+ — (.+)$", text, re.M).group(1)
    blocked = re.search(r"^\*\*Blocked by:\*\*(.*?)^\*\*", text, re.M | re.S).group(1)
    issues[num] = dict(
        path=f.relative_to(ROOT).as_posix(),
        group=f.parent.name,
        title=title,
        status=field(text, "Status"),
        model=field(text, "Model"),
        effort=field(text, "Effort"),
        human=field(text, "Human step"),
        blocked=re.findall(r"^- (\d+) —", blocked, re.M),
    )

done = {n for n, i in issues.items() if i["status"] == "done"}
ready = [n for n, i in issues.items() if i["status"] != "done" and set(i["blocked"]) <= done]


def link(n):
    return f"[{n} {issues[n]['title']}]({issues[n]['path']})"


out = [
    "# eds-ui build map",
    "",
    "Generated by `python3 build_map.py`. Do not edit by hand; rerun after changing an issue.",
    "",
    f"**Progress:** {len(done)} of {len(issues)} done.",
    "",
    "## Next up (unblocked, not done)",
    "",
]
out += [f"- {link(n)} — `{issues[n]['model']}` / `{issues[n]['effort']}`"
        + (f" — **you:** {issues[n]['human']}" if issues[n]["human"] else "") for n in ready]

out += ["", "## Your manual steps", ""]
out += [f"- {link(n)}: {i['human']}" for n, i in issues.items() if i["human"]]

group = None
for n, i in issues.items():
    if i["group"] != group:
        group = i["group"]
        out += ["", f"## {group}", "", "| # | Issue | Status | Model | Effort | Blocked by |", "|---|---|---|---|---|---|"]
    status = "✅ done" if i["status"] == "done" else ("▶ ready" if n in ready else "⏳ blocked")
    out.append(f"| {n} | [{i['title']}]({i['path']}) | {status} | {i['model']} | {i['effort']} | {', '.join(i['blocked']) or '—'} |")

(ROOT / "MAP.md").write_text("\n".join(out) + "\n")
print(f"MAP.md: {len(issues)} issues, {len(done)} done, {len(ready)} ready")
